#!/usr/bin/env python3
"""Generates the dispatch-strategy benchmark fixture (plan L5-6).

The adaptive dispatcher (design section 6.3) chooses between two routing strategies by message
count: a type-pattern chain below a threshold, a frozen-dictionary jump table above it. To set
that threshold from data rather than guesswork, DispatchStrategyBenchmarks needs both strategies
materialised at a range of message counts -- which means a range of distinct message types.

This script emits those types and dispatchers into Generated/DispatchFixture.g.cs. It is
committed output: rerun it only when SIZES changes.

    python3 benchmarks/generate-dispatch-fixture.py
"""

import os

# The message-count sizes the benchmark measures. Keep in sync with the [Params] on
# DispatchStrategyBenchmarks.
SIZES = [4, 8, 16, 32, 64, 128]
MAX_SIZE = max(SIZES)

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_PATH = os.path.join(SCRIPT_DIR, "Quantix.Benchmarks", "Generated", "DispatchFixture.g.cs")


def build() -> str:
    lines: list[str] = []
    add = lines.append

    add("// <auto-generated/>")
    add("//")
    add("// Generated by benchmarks/generate-dispatch-fixture.py -- do not edit by hand.")
    add("// Marker messages plus the two routing strategies the adaptive dispatcher chooses")
    add("// between (design section 6.3): a type-pattern chain and a frozen-dictionary jump table.")
    add("")
    add("using System;")
    add("using System.Collections.Frozen;")
    add("using System.Collections.Generic;")
    add("")
    add("namespace Quantix.Benchmarks;")
    add("")

    # Distinct marker message types, file-local to this generated file.
    for i in range(MAX_SIZE):
        add(f"file sealed class DispatchMsg{i} {{ }}")
    add("")

    add("/// <summary>The type-pattern and frozen-dictionary dispatchers measured by L5-6.</summary>")
    add("internal static class DispatchFixture")
    add("{")

    # Type-pattern dispatchers: one sequential 'is' check per message type.
    for n in SIZES:
        add(f"    private static int TypePattern{n}(object message)")
        add("    {")
        for k in range(n):
            add(f"        if (message is DispatchMsg{k}) return {k};")
        add("        return -1;")
        add("    }")
        add("")

    # Frozen-dictionary dispatchers: a single type lookup.
    for n in SIZES:
        add(f"    private static readonly FrozenDictionary<Type, int> Frozen{n} =")
        add("        new Dictionary<Type, int>")
        add("        {")
        for k in range(n):
            add(f"            {{ typeof(DispatchMsg{k}), {k} }},")
        add("        }.ToFrozenDictionary();")
        add("")
        add(f"    private static int FrozenDispatch{n}(object message)")
        add(f"        => Frozen{n}.TryGetValue(message.GetType(), out int value) ? value : -1;")
        add("")

    add("    /// <summary>Returns the type-pattern dispatcher for the given message-count size.</summary>")
    add("    public static Func<object, int> TypePatternDispatcher(int size) => size switch")
    add("    {")
    for n in SIZES:
        add(f"        {n} => TypePattern{n},")
    add("        _ => throw new ArgumentOutOfRangeException(nameof(size)),")
    add("    };")
    add("")

    add("    /// <summary>Returns the frozen-dictionary dispatcher for the given message-count size.</summary>")
    add("    public static Func<object, int> FrozenDispatcher(int size) => size switch")
    add("    {")
    for n in SIZES:
        add(f"        {n} => FrozenDispatch{n},")
    add("        _ => throw new ArgumentOutOfRangeException(nameof(size)),")
    add("    };")
    add("")

    add("    /// <summary>Returns a mid-chain message — the average-case lookup for the type-pattern chain.</summary>")
    add("    public static object RepresentativeMessage(int size) => size switch")
    add("    {")
    for n in SIZES:
        add(f"        {n} => new DispatchMsg{n // 2}(),")
    add("        _ => throw new ArgumentOutOfRangeException(nameof(size)),")
    add("    };")
    add("}")
    add("")

    return "\n".join(lines)


def main() -> None:
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(build())
    print(f"Wrote {OUT_PATH} ({MAX_SIZE} message types, sizes {SIZES}).")


if __name__ == "__main__":
    main()
